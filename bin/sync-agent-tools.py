def _toml_str(value) -> str:
    # JSON string escaping is valid TOML basic-string escaping for everything we emit.
    return json.dumps(str(value), ensure_ascii=False)


def render_codex_block(manifest: dict) -> str:
    lines = [BEGIN_MARKER]
    for name, spec in manifest["mcp_servers"].items():
        lines.append(f"[mcp_servers.{name}]")
        lines.append(f"command = {_toml_str(spec['command'])}")
        args = ", ".join(_toml_str(a) for a in (spec.get("args") or []))
        lines.append(f"args = [{args}]")
        env = expand_env_values(spec.get("env"))
        if env:
            lines.append("")
            lines.append(f"[mcp_servers.{name}.env]")
            for k, v in env.items():
                lines.append(f"{k} = {_toml_str(v)}")
        lines.append("")
    lines.append(END_MARKER)
    return "\n".join(lines)


def strip_toml_table(text: str, table_name: str) -> str:
    """Remove a TOML table (and its dotted sub-tables) by name; everything else is kept."""
    out, skip = [], False
    for line in text.split("\n"):
        stripped = line.strip()
        if stripped.startswith("["):
            header = stripped.strip("[]").strip()
            skip = header == table_name or header.startswith(table_name + ".")
            if skip:
                continue
        if not skip:
            out.append(line)
    return "\n".join(out)


def merge_codex_config(text: str, manifest: dict) -> str:
    """Return config.toml text with the managed block replaced (or appended on first run)."""
    if BEGIN_MARKER in text and END_MARKER in text:
        pre = text.split(BEGIN_MARKER)[0].rstrip("\n")
        post = text.split(END_MARKER, 1)[1].lstrip("\n")
    else:
        # First run: drop any unmarked hand-added tables for the same servers so re-running
        # does not leave duplicate [mcp_servers.x] tables (a TOML parse error) behind.
        pre, post = text.rstrip("\n"), ""
        for name in manifest["mcp_servers"]:
            pre = strip_toml_table(pre, f"mcp_servers.{name}").rstrip("\n")
    block = render_codex_block(manifest)
    head = (pre + "\n\n") if pre else ""
    return head + block + ("\n\n" + post if post else "\n")


def codex_sidecar(meta: dict) -> str:
    return ("interface:\n"
            f"  display_name: {_toml_str(meta['display_name'])}\n"
            f"  short_description: {_toml_str(meta['short_description'])}\n"
            f"  default_prompt: {_toml_str(meta['default_prompt'])}\n")


def sync_codex(seat_name: str, seat: dict, manifest: dict, dry_run: bool, **_kw) -> None:
    config_file = resolve_path(seat["config_file"])
    text = config_file.read_text(encoding="utf-8") if config_file.is_file() else ""
    new_text = merge_codex_config(text, manifest)
    if new_text == text:
        print(f"  [{seat_name}] config.toml managed block already current")
    elif dry_run:
        print(f"  [{seat_name}] would rewrite managed block in {config_file}")
    else:
        config_file.parent.mkdir(parents=True, exist_ok=True)
        config_file.write_text(new_text, encoding="utf-8", newline="\n")
        print(f"  [{seat_name}] config.toml managed block updated")

    skills_dir = resolve_path(seat["skills_dir"])

    def keep(name: str) -> set:
        spec = manifest["skills"][name]
        return {"agents/openai.yaml"} if isinstance(spec, dict) and spec.get("codex_meta") else set()

    sync_skills(seat_name, skills_dir, manifest, dry_run, keep)
    for skill_name, spec in manifest["skills"].items():
        meta = spec.get("codex_meta") if isinstance(spec, dict) else None
        if not meta:
            continue
        dest = skills_dir / skill_name / "agents" / "openai.yaml"
        content = codex_sidecar(meta)
        if dest.is_file() and dest.read_text(encoding="utf-8") == content:
            continue
        if dry_run:
            print(f"  [{seat_name}] would write {dest}")
        else:
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_text(content, encoding="utf-8", newline="\n")


# ---------------------------------------------------------------------------
# Gemini CLI / Antigravity seat
# ---------------------------------------------------------------------------

def merge_gemini_settings(data: dict, manifest: dict) -> dict:
    data = dict(data)
    servers = dict(data.get("mcpServers") or {})
    for name, spec in manifest["mcp_servers"].items():
        entry = {"command": spec["command"], "args": [str(a) for a in (spec.get("args") or [])]}
        env = expand_env_values(spec.get("env"))
        if env:
            entry["env"] = env
        if spec.get("trust") is not None:
            entry["trust"] = bool(spec["trust"])
        servers[name] = entry
    data["mcpServers"] = servers
    return data


def sync_gemini(seat_name: str, seat: dict, manifest: dict, dry_run: bool, **_kw) -> None:
    settings_file = resolve_path(seat["settings_file"])
    old = json.loads(settings_file.read_text(encoding="utf-8")) if settings_file.is_file() else {}
    new = merge_gemini_settings(old, manifest)
    if new == old:
        print(f"  [{seat_name}] settings.json mcpServers already current")
    elif dry_run:
        print(f"  [{seat_name}] would update mcpServers in {settings_file}")
    else:
        settings_file.parent.mkdir(parents=True, exist_ok=True)
        settings_file.write_text(json.dumps(new, indent=2) + "\n", encoding="utf-8", newline="\n")
        print(f"  [{seat_name}] settings.json mcpServers updated")
    sync_skills(seat_name, resolve_path(seat["skills_dir"]), manifest, dry_run)


# ---------------------------------------------------------------------------
# shared instructions file ("contract")
# ---------------------------------------------------------------------------

def render_contract(shared: str, source_label: str, header: str, render: str = "full") -> str:
    stamp = f"<!-- contract-sha256: {hashlib.sha256(shared.encode('utf-8')).hexdigest()} -->"
    notice = CONTRACT_NOTICE.format(source=source_label)
    if render == "pointer":
        return f"{header.strip()}\n\n{notice}\n{stamp}\n"
    return f"{header.strip()}\n\n{notice}\n{stamp}\n\n---\n\n{shared}\n"


def sync_contract(manifest: dict, dry_run: bool, only: str | None = None) -> int:
    """Render one shared instructions file into each seat's user-level instruction file.

    Copy, not import: Claude Code expands `@path` imports in a PROJECT CLAUDE.md but has not
    reliably done so for a user-scope one, and symlinks need elevated rights on Windows. A
    rendered copy with a hash stamp works everywhere, and the stamp makes drift detectable.
    """
    spec = manifest.get("contract")
    if not spec:
        return 0
    source = resolve_path(spec["source"])
    if not source.is_file():
        print(f"  CONTRACT SOURCE MISSING: {source} — contract sync skipped", file=sys.stderr)
        return 1
    shared = source.read_text(encoding="utf-8").strip()
    label = spec["source"]
    render = spec.get("render", "full")
    changed = 0
    for seat_name, target in (spec.get("targets") or {}).items():
        if only and seat_name != only:
            continue
        if not target.get("enabled", False):
            print(f"  [{seat_name}] contract: disabled in manifest, skipped")
            continue
        dest = resolve_path(target["file"])
        rendered = render_contract(shared, label, target.get("header", ""), render)
        if dest.is_file() and dest.read_text(encoding="utf-8") == rendered:
            print(f"  [{seat_name}] contract: already current ({dest})")
            continue
        changed += 1
        if dry_run:
            print(f"  [{seat_name}] contract: WOULD write {dest} ({len(rendered)} chars)")
            continue
        if dest.is_file():
            shutil.copy2(dest, dest.with_suffix(dest.suffix + ".bak-contract"))
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(rendered, encoding="utf-8", newline="\n")
        print(f"  [{seat_name}] contract: wrote {dest} ({len(rendered)} chars)")
    print(f"Contract sync: {changed} file(s) {'would change' if dry_run else 'updated'}.")
    return 0


# ---------------------------------------------------------------------------
# main
# ---------------------------------------------------------------------------

DISPATCH = {
    "claude-code": sync_claude_code,
    "codex": sync_codex,
    "gemini": sync_gemini,
}


def find_manifest(explicit: str | None) -> Path:
    if explicit:
        return resolve_path(explicit, Path.cwd())
    if DEFAULT_MANIFEST.is_file():
        return DEFAULT_MANIFEST
    raise SystemExit(
        f"No manifest at {DEFAULT_MANIFEST}.\n"
        "Copy config/agent-tools.example.yaml to config/agent-tools.yaml, edit the seats for "
        "your machine, then re-run (or pass --manifest).")


def main(argv=None, runner: Runner = _default_runner) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--manifest", help="manifest path (default: config/agent-tools.yaml)")
    ap.add_argument("--dry-run", action="store_true", help="report changes, write nothing")
    ap.add_argument("--seat", help="sync only this seat")
    ap.add_argument("--contract-only", action="store_true",
                    help="only re-render the shared instructions file into each seat")
    ap.add_argument("--no-gate", action="store_true",
                    help="EMERGENCY: ship skills without validating them first")
    args = ap.parse_args(argv)

    manifest = load_manifest(find_manifest(args.manifest))

    if args.contract_only:
        return sync_contract(manifest, args.dry_run, args.seat)

    if args.no_gate:
        print("WARNING: --no-gate set, shipping skills WITHOUT validation.\n", file=sys.stderr)
    else:
        print("Gate: validating every managed skill before touching any seat...")
        if not run_gate(manifest):
            print("\nGate FAILED. Nothing was synced. Fix the skill(s) above "
                  "(or --no-gate in an emergency).", file=sys.stderr)
            return 1
        print("Gate passed.\n")

    rc = sync_contract(manifest, args.dry_run, args.seat) if manifest.get("contract") else 0

    seats = enabled_seats(manifest, args.seat)
    if args.seat and not seats:
        print(f"No enabled seat named {args.seat!r} in the manifest.", file=sys.stderr)
        return 2
    for seat_name, seat in seats.items():
        fn = DISPATCH.get(seat.get("kind"))
        if fn is None:
            print(f"  [{seat_name}] SKIPPED: no compiler for kind {seat.get('kind')!r} yet "
                  f"(known: {', '.join(DISPATCH)})")
            continue
        print(f"Syncing seat: {seat_name} ({seat['kind']})")
        if fn is sync_claude_code:
            fn(seat_name, seat, manifest, args.dry_run, runner=runner)
        else:
            fn(seat_name, seat, manifest, args.dry_run)

    print("\nDry run complete, no files changed." if args.dry_run else "\nDone.")
    return rc


if __name__ == "__main__":
    sys.exit(main())
