#!/usr/bin/env python3
"""sync-agent-tools.py — apply ONE manifest of MCP servers + skills to every agent "seat".

A seat is one place an agent reads its configuration from: a Claude Code config dir
(`~/.claude`, or a second one selected with CLAUDE_CONFIG_DIR for a second subscription), a
Codex install (`~/.codex`), a Gemini CLI / Antigravity install (`~/.gemini`).

WHY THIS EXISTS
No agent CLI supports "include this external file" for its MCP-server config, and installed
skills are COPIES, not links. So the moment you run two profiles (or two tools) they drift: a
skill fixed in one place is still broken in the other, an MCP server added to one profile is
silently missing from the next, and a shared rules file edited in one copy is stale in the rest.
Nothing errors; you find out when a session behaves differently for no visible reason. This
script is the practical substitute for an include directive: one manifest, one command,
re-applied everywhere.

WHAT IT DOES, per enabled seat in the manifest
  claude-code  `claude mcp remove` + `claude mcp add -s user` for each managed server (scoped to
               the seat with CLAUDE_CONFIG_DIR), skills mirrored into <config_dir>/skills/<name>/
  codex        a marked, managed `[mcp_servers.*]` block in config.toml (everything outside the
               markers is preserved), skills mirrored + an agents/openai.yaml sidecar
  gemini       the `mcpServers` entries in settings.json (other keys preserved), skills mirrored
  contract     (optional) one shared instructions file rendered into each seat's user-level
               instruction file (CLAUDE.md / AGENTS.md / GEMINI.md) with a hash stamp

THE GATE
Every real sync first validates every managed skill: SKILL.md must parse (the shared
bin/skill_policy.py contract — BOM-free frontmatter whose name equals its directory) and every
.py helper inside the skill must compile. If ANY skill fails, nothing is touched. Shipping a
broken skill to four seats at once is the failure this prevents. `--no-gate` bypasses it for an
emergency only.

ONLY MANAGED THINGS ARE TOUCHED
Servers and skills not named in the manifest are left alone. A managed skill directory IS
mirrored, though: files in the seat copy that no longer exist in the source are removed, so a
deleted reference file does not linger in one profile forever.

Usage:
  python bin/sync-agent-tools.py --dry-run          # show what would change, touch nothing
  python bin/sync-agent-tools.py                    # gate, then apply to every enabled seat
  python bin/sync-agent-tools.py --seat claude-work # one seat only
  python bin/sync-agent-tools.py --contract-only    # just re-render the shared instructions file
  python bin/sync-agent-tools.py --manifest path/to/agent-tools.yaml

Manifest: config/agent-tools.yaml (copy config/agent-tools.example.yaml and edit it). Paths in
the manifest may use `~` and environment variables; relative paths resolve against the repo root.
Requires PyYAML for .yaml manifests (a .json manifest with the same shape needs nothing).
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import py_compile
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Callable

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(Path(__file__).resolve().parent))

DEFAULT_MANIFEST = REPO / "config" / "agent-tools.yaml"
EXAMPLE_MANIFEST = REPO / "config" / "agent-tools.example.yaml"

BEGIN_MARKER = ("# BEGIN managed mcp servers (generated by sync-agent-tools.py from the "
                "agent-tools manifest; edit the manifest and re-run, do not hand-edit)")
END_MARKER = "# END managed mcp servers"

CONTRACT_NOTICE = (
    "<!-- GENERATED FILE. DO NOT HAND-EDIT.\n"
    "     Everything below the header is rendered verbatim from {source}.\n"
    "     Edit that file, then run: python bin/sync-agent-tools.py --contract-only\n"
    "     Hand-edits here are silently overwritten on the next sync. -->"
)

# Never copied into a seat: build output, caches, local installs, editor backups.
SKIP_NAMES = {"__pycache__", "node_modules", ".git", ".DS_Store", "captures"}
SKIP_SUFFIXES = (".pyc", ".pyo")

Runner = Callable[[list, dict], "subprocess.CompletedProcess"]

for _s in (sys.stdout, sys.stderr):
    try:
        _s.reconfigure(encoding="utf-8", errors="replace")
    except Exception:  # noqa: BLE001
        pass


# ---------------------------------------------------------------------------
# manifest + paths
# ---------------------------------------------------------------------------

def resolve_path(value: str | os.PathLike, base: Path = REPO) -> Path:
    """`~` and $VARS expanded; a relative path is relative to the repo, never the CWD."""
    p = Path(os.path.expandvars(os.path.expanduser(str(value))))
    return p if p.is_absolute() else (base / p)


def load_manifest(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    if path.suffix.lower() == ".json":
        data = json.loads(text)
    else:
        try:
            import yaml
        except ImportError as e:  # pragma: no cover - depends on the environment
            raise SystemExit("PyYAML is required for a .yaml manifest "
                             "(pip install PyYAML), or use a .json manifest") from e
        data = yaml.safe_load(text)
    if not isinstance(data, dict):
        raise SystemExit(f"manifest {path} is not a mapping")
    data.setdefault("seats", {})
    data["mcp_servers"] = data.get("mcp_servers") or {}
    data["skills"] = data.get("skills") or {}
    return data


def skill_source_dir(spec: dict | str) -> Path:
    """A skill's source may name its directory or its SKILL.md; either way, ship the directory."""
    src = spec["source"] if isinstance(spec, dict) else spec
    p = resolve_path(src)
    return p.parent if p.name == "SKILL.md" else p


def enabled_seats(manifest: dict, only: str | None = None) -> dict:
    seats = {}
    for name, seat in (manifest.get("seats") or {}).items():
        if only and name != only:
            continue
        if seat.get("enabled", True) is False:
            continue
        seats[name] = seat
    return seats


def expand_env_values(env: dict | None) -> dict:
    """Env values may reference the caller's environment (`${MY_TOKEN}`) so secrets stay out of
    the manifest. An unset variable is left as-is and reported, never silently emptied."""
    out = {}
    for k, v in (env or {}).items():
        val = os.path.expandvars(str(v))
        if "$" in val:
            print(f"  WARNING: env {k} references an unset variable: {v}", file=sys.stderr)
        out[k] = val
    return out


# ---------------------------------------------------------------------------
# gate
# ---------------------------------------------------------------------------

def gate_skill(name: str, src: Path) -> list[str]:
    """Problems that make this skill unfit to ship. Empty list == shippable."""
    from skill_policy import check_skill_bytes

    skill_md = src / "SKILL.md"
    if not src.is_dir():
        return [f"source directory does not exist: {src}"]
    if not skill_md.is_file():
        return [f"no SKILL.md in {src}"]
    problems = check_skill_bytes(skill_md.read_bytes(), expected_name=name)
    for py in sorted(src.rglob("*.py")):
        if any(part in SKIP_NAMES for part in py.parts):
            continue
        try:
            with tempfile.TemporaryDirectory() as td:
                py_compile.compile(str(py), cfile=str(Path(td) / "x.pyc"), doraise=True)
        except py_compile.PyCompileError as e:
            problems.append(f"{py.relative_to(src)} does not compile: {e.msg.strip()}")
    return problems


def run_gate(manifest: dict) -> bool:
    ok = True
    for name, spec in manifest["skills"].items():
        problems = gate_skill(name, skill_source_dir(spec))
        print(f"  [gate] {name}: {'ok' if not problems else 'FAILED'}")
        for p in problems:
            print(f"         - {p}")
        ok &= not problems
    return ok


# ---------------------------------------------------------------------------
# skill mirroring
# ---------------------------------------------------------------------------

def _wanted_files(src: Path) -> dict[str, Path]:
    out = {}
    for p in sorted(src.rglob("*")):
        rel_parts = p.relative_to(src).parts
        if any(part in SKIP_NAMES for part in rel_parts):
            continue
        if not p.is_file() or p.suffix in SKIP_SUFFIXES or ".bak" in p.name:
            continue
        out["/".join(rel_parts)] = p
    return out


def mirror_skill(src: Path, dest: Path, dry_run: bool, keep: set[str] = frozenset()) -> dict:
    """Make dest an exact copy of src (minus junk). Returns {"copied": [...], "removed": [...]}.

    `keep` lists dest-relative files this script itself generates (e.g. a Codex sidecar) that
    must survive the mirror. Local installs (node_modules) in dest are never touched.
    """
    wanted = _wanted_files(src)
    copied, removed = [], []
    for rel, s in wanted.items():
        d = dest / rel
        if d.is_file() and d.read_bytes() == s.read_bytes():
            continue
        copied.append(rel)
        if not dry_run:
            d.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(s, d)
    if dest.is_dir():
        for p in sorted(dest.rglob("*"), reverse=True):
            rel_parts = p.relative_to(dest).parts
            if any(part in SKIP_NAMES for part in rel_parts):
                continue
            rel = "/".join(rel_parts)
            if p.is_file() and rel not in wanted and rel not in keep:
                removed.append(rel)
                if not dry_run:
                    p.unlink()
            elif p.is_dir() and not dry_run and not any(p.iterdir()):
                p.rmdir()
    return {"copied": copied, "removed": sorted(removed)}


def sync_skills(seat_name: str, skills_dir: Path, manifest: dict, dry_run: bool,
                keep: Callable[[str], set] = lambda _n: set()) -> None:
    for skill_name, spec in manifest["skills"].items():
        res = mirror_skill(skill_source_dir(spec), skills_dir / skill_name, dry_run,
                           keep(skill_name))
        if res["copied"] or res["removed"]:
            verb = "would update" if dry_run else "updated"
            print(f"  [{seat_name}] skill {skill_name}: {verb} "
                  f"({len(res['copied'])} copied, {len(res['removed'])} removed)")


# ---------------------------------------------------------------------------
# Claude Code seats
# ---------------------------------------------------------------------------

def _default_runner(cmd: list, env: dict) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, env={**os.environ, **env}, capture_output=True, text=True,
                          encoding="utf-8", errors="replace")


def claude_add_command(claude: str, name: str, spec: dict) -> list[str]:
    cmd = [claude, "mcp", "add", name, "-s", "user"]
    for k, v in expand_env_values(spec.get("env")).items():
        cmd += ["-e", f"{k}={v}"]
    return cmd + ["--", spec["command"], *[str(a) for a in (spec.get("args") or [])]]


def sync_claude_code(seat_name: str, seat: dict, manifest: dict, dry_run: bool,
                     runner: Runner = _default_runner) -> None:
    config_dir = resolve_path(seat["config_dir"])
    env = {"CLAUDE_CONFIG_DIR": str(config_dir)}

    if manifest["mcp_servers"]:
        claude = shutil.which("claude") or "claude"
        for name, spec in manifest["mcp_servers"].items():
            if dry_run:
                print(f"  [{seat_name}] would re-register mcp server: {name}")
                continue
            runner([claude, "mcp", "remove", name, "-s", "user"], env)
            result = runner(claude_add_command(claude, name, spec), env)
            status = "ok" if result.returncode == 0 else f"FAILED: {(result.stderr or '').strip()}"
            print(f"  [{seat_name}] mcp server {name}: {status}")

    sync_skills(seat_name, config_dir / "skills", manifest, dry_run)


